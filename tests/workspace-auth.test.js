const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

test('login, messages, themes and disabled modules enforce user/admin roles', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'vncs-workspace-'));
  process.env.WORKSPACE_STATE_FILE = path.join(dir, 'state.json');
  const app = require('../app');
  const server = await new Promise(resolve => { const instance = app.listen(0, '127.0.0.1', () => resolve(instance)); });
  t.after(() => { server.closeAllConnections(); server.close(); fs.rmSync(dir, { recursive: true, force: true }); delete process.env.WORKSPACE_STATE_FILE; });
  const base = `http://127.0.0.1:${server.address().port}`;
  const get = (url, cookie) => fetch(base + url, { headers: cookie ? { Cookie: cookie } : {}, redirect: 'manual' });
  const login = async (username, password, remember = false) => {
    const page = await get('/login'); const html = await page.text();
    const csrf = html.match(/name="_csrf" value="([^"]+)"/)[1];
    const initialCookie = page.headers.get('set-cookie').split(';')[0];
    const response = await fetch(base + '/login', { method: 'POST', redirect: 'manual', headers: { Cookie: initialCookie, 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ _csrf: csrf, username, password, next: '/home', ...(remember ? { remember: 'on' } : {}) }) });
    const cookies = response.headers.getSetCookie();
    return { response, cookie: cookies.find(value => value.startsWith('vncs.sid='))?.split(';')[0], rememberCookie: cookies.findLast(value => value.startsWith('vncs.remember=') && !value.includes('Expires=Thu, 01 Jan 1970'))?.split(';')[0], savedUserCookie: cookies.findLast(value => value.startsWith('vncs.saved-user=') && !value.includes('Expires=Thu, 01 Jan 1970'))?.split(';')[0], cookies };
  };
  const settings = html => JSON.parse(html.match(/window\.workspaceSettings = (\{[^;]+\}); document/)[1]);
  const json = (cookie, csrf, method, url, body) => fetch(base + url, { method, headers: { Cookie: cookie, 'Content-Type': 'application/json', 'X-CSRF-Token': csrf, Accept: 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body), redirect: 'manual' });

  assert.equal((await get('/home')).status, 302);
  const loginPage = await (await get('/login')).text();
  assert.match(loginPage, /rel="icon" type="image\/svg\+xml" href="\/workspace\/favicon\.svg\?v=2"/);
  const favicon = await get('/workspace/favicon.svg');
  assert.equal(favicon.status, 200);
  assert.match(favicon.headers.get('content-type'), /image\/svg\+xml/);
  const iconSvg = await favicon.text();
  assert.match(iconSvg, /<svg[^>]+viewBox="0 0 64 64"/);
  assert.match(iconSvg, /id="shield"/);
  assert.doesNotMatch(iconSvg, /<circle/);
  const loginScript = await get('/workspace/login.js');
  assert.equal(loginScript.status, 200);
  const loginJavaScript = await loginScript.text();
  assert.match(loginJavaScript, /navigator\.credentials\.store/);
  assert.match(loginJavaScript, /navigator\.credentials\.get/);
  assert.doesNotMatch(loginJavaScript, /localStorage|sessionStorage/);
  assert.equal((await get('/scope-review')).headers.get('location').startsWith('/login'), true);
  assert.equal((await json('', '', 'POST', '/api/pyc-transition', {})).status, 401);
  assert.equal((await login('vncs', 'wrong')).response.status, 401);
  const jsonLoginPage = await get('/login');
  const jsonLoginCsrf = (await jsonLoginPage.text()).match(/name="_csrf" value="([^"]+)"/)[1];
  const jsonLoginResponse = await fetch(base + '/login', { method: 'POST', redirect: 'manual', headers: { Cookie: jsonLoginPage.headers.get('set-cookie').split(';')[0], Accept: 'application/json', 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ _csrf: jsonLoginCsrf, username: 'mb', password: 'mb', remember: 'on', next: '/home' }) });
  assert.equal(jsonLoginResponse.status, 200);
  assert.deepEqual(await jsonLoginResponse.json(), { redirect: '/home' });
  assert.match(jsonLoginResponse.headers.getSetCookie().join(' '), /vncs\.saved-user=mb/);

  const user = await login('vncs', 'vncs'); assert.equal(user.response.status, 302);
  const homeHtml = await (await get('/home', user.cookie)).text();
  assert.match(homeHtml, /href="\/scope-review"/);
  assert.match(homeHtml, /window\.workspaceSettings/);
  assert.match(homeHtml, /href="\/workspace\/favicon\.svg\?v=2"/);
  const userSettings = settings(homeHtml); assert.equal(userSettings.role, 'user');
  const cssResponse = await get('/workspace/theme.css', user.cookie);
  assert.equal(cssResponse.status, 200);
  const css = await cssResponse.text();
  for (const themeName of ['dark', 'light', 'pink', 'red']) assert.match(css, new RegExp(`data-theme="${themeName}"`));
  assert.equal((await get('/workspace/ui.js', user.cookie)).status, 200);
  for (const url of ['/pending-comment', '/excel', '/pentest-report', '/ai-checklist/decision', '/home/pyc-transition', '/manday', '/aes']) {
    const response = await get(url, user.cookie);
    assert.equal(response.status, 200, url);
    const page = await response.text();
    assert.match(page, /\/workspace\/theme\.css/, url);
    assert.match(page, /href="\/workspace\/favicon\.svg\?v=2"/, url);
  }
  assert.equal((await get('/admin', user.cookie)).status, 403);
  const sent = await json(user.cookie, userSettings.csrf, 'POST', '/workspace/messages', { senderName: 'Nguyễn An', content: 'Chúc đội ngũ một ngày tốt lành!' });
  assert.equal(sent.status, 201);
  const theme = await json(user.cookie, userSettings.csrf, 'POST', '/workspace/theme', { theme: 'pink' });
  assert.equal(theme.status, 200);
  const scopeHtml = await (await get('/scope-review', user.cookie)).text();
  assert.match(scopeHtml, /"theme":"pink"/);

  const admin = await login('admin', 'Long@123'); assert.equal(admin.response.status, 302);
  const adminHtml = await (await get('/admin', admin.cookie)).text();
  assert.match(adminHtml, /Nguyễn An/); assert.match(adminHtml, /Tài khoản: vncs/);
  const adminSettings = settings(adminHtml);
  const disable = await json(admin.cookie, adminSettings.csrf, 'POST', '/admin/modules/scope-review', { enabled: false });
  assert.equal(disable.status, 200);
  assert.doesNotMatch(await (await get('/home', user.cookie)).text(), /href="\/scope-review"/);
  assert.equal((await get('/scope-review', user.cookie)).status, 404);
  assert.equal((await json(user.cookie, userSettings.csrf, 'POST', '/scope-review/prepare', {})).status, 403);
  assert.equal((await get('/scope-review', admin.cookie)).status, 200);
  assert.equal((await json(user.cookie, userSettings.csrf, 'POST', '/admin/modules/scope-review', { enabled: true })).status, 403);

  const messageId = JSON.parse(fs.readFileSync(process.env.WORKSPACE_STATE_FILE, 'utf8')).messages[0].id;
  assert.equal((await json(admin.cookie, adminSettings.csrf, 'POST', `/admin/messages/${messageId}/read`, { read: true })).status, 200);
  assert.equal((await json(admin.cookie, adminSettings.csrf, 'DELETE', `/admin/messages/${messageId}`)).status, 200);
  const logout = await fetch(base + '/logout', { method: 'POST', redirect: 'manual', headers: { Cookie: user.cookie, 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ _csrf: userSettings.csrf }) });
  assert.equal(logout.status, 302);
  assert.equal((await get('/home', user.cookie)).status, 302);
  const remembered = await login('mb', 'mb', true);
  assert.equal(remembered.response.status, 302);
  assert.ok(remembered.rememberCookie?.startsWith('vncs.remember='));
  assert.equal(remembered.savedUserCookie, 'vncs.saved-user=mb');
  assert.match(remembered.cookies.join(' '), /HttpOnly/);
  assert.match(remembered.cookies.join(' '), /Max-Age=2592000/);
  const savedState = fs.readFileSync(process.env.WORKSPACE_STATE_FILE, 'utf8');
  assert.equal(savedState.includes(remembered.rememberCookie.split('=')[1].split('.')[1]), false, 'the raw secret must not be stored');
  const restored = await get('/home', remembered.rememberCookie);
  assert.equal(restored.status, 200, 'remember cookie restores a new session without a password');
  const restoredCookie = restored.headers.getSetCookie().find(value => value.startsWith('vncs.sid='))?.split(';')[0];
  const restoredSettings = settings(await restored.text());
  assert.equal(restoredSettings.username, 'mb');
  const revoked = await fetch(base + '/logout', { method: 'POST', redirect: 'manual', headers: { Cookie: `${restoredCookie}; ${remembered.rememberCookie}`, 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ _csrf: restoredSettings.csrf }) });
  assert.equal(revoked.status, 302);
  assert.equal((await get('/home', remembered.rememberCookie)).status, 302, 'logout revokes remembered access');
  const savedLoginPage = await (await get('/login', remembered.savedUserCookie)).text();
  assert.match(savedLoginPage, /name="username"[^>]*value="mb"/);
  assert.match(savedLoginPage, /name="remember"[^>]*checked/);
});
